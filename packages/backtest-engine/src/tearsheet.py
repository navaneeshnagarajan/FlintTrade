_BRAND_HEADER_TEMPLATE = textwrap.dedent("""\
    <div class="ft-header">
      <span class="ft-logo">FlintTrade</span>
      <span class="ft-title">{title}</span>
    </div>
""")

_BRAND_FOOTER = textwrap.dedent("""\
    <div class="ft-footer">
      Generated by FlintTrade Backtest Engine &mdash; for informational purposes only.
      Past performance does not guarantee future results.
    </div>
""")

_STUB_TEMPLATE = textwrap.dedent("""\
    <!DOCTYPE html>
    <html lang="en">
    <head>
      <meta charset="UTF-8">
      <title>FlintTrade — {title}</title>
      {css}
    </head>
    <body style="background:#0a0a0f;color:#e8e8f0;font-family:'Inter',system-ui,sans-serif;padding:32px;">
      {header}
      <div style="margin:40px auto;max-width:600px;text-align:center;padding:48px;
                  background:#16161f;border-radius:12px;border:1px solid #2a2a3a;">
        <h2 style="color:#9090b0;">Tearsheet Unavailable</h2>
        <p style="color:#707090;">{message}</p>
        <code style="background:#0a0a0f;padding:8px 16px;border-radius:6px;
                     color:#c8c8e8;font-size:0.85rem;">pip install quantstats</code>
      </div>
      {footer}
    </body>
    </html>
""")


def _brand_html(inner_html: str, title: str) -> str:
    """Inject FlintTrade branding into an existing HTML string.

    Prepends the branded header and appends the footer. Handles both full
    ``<!DOCTYPE html>`` documents from QuantStats and bare HTML fragments.

    Args:
        inner_html: Raw HTML from QuantStats or another source.
        title: Strategy or report title shown in the header bar.

    Returns:
        Branded HTML string.
    """
    header = _BRAND_HEADER_TEMPLATE.format(title=title)
    injection = _BRAND_CSS + "\n" + header

    # Insert after <body> if present; prepend otherwise.
    if "<body" in inner_html:
        insert_after = inner_html.find(">", inner_html.find("<body")) + 1
        branded = (
            inner_html[:insert_after]
            + "\n"
            + injection
            + inner_html[insert_after:]
        )
    else:
        branded = injection + inner_html

    # Append footer before </body> if present; otherwise append.
    if "</body>" in branded:
        branded = branded.replace("</body>", _BRAND_FOOTER + "\n</body>")
    else:
        branded += "\n" + _BRAND_FOOTER

    return branded


def _stub_html(title: str, message: str) -> str:
    """Return a minimal branded stub page when QuantStats is unavailable.

    Args:
        title: Report title.
        message: Human-readable reason the tearsheet could not be generated.

    Returns:
        Self-contained HTML string.
    """
    return _STUB_TEMPLATE.format(
        title=title,
        css=_BRAND_CSS,
        header=_BRAND_HEADER_TEMPLATE.format(title=title),
        message=message,
        footer=_BRAND_FOOTER,
    )


