"""QuantStats tearsheet generation for FlintTrade backtest results.

Wraps the QuantStats library (optional dependency) to produce HTML tearsheets,
compact snapshots, and multi-strategy comparison reports. All functions degrade
gracefully when QuantStats is not installed, returning an informative HTML
stub instead of raising an exception.

References:
    - marketcalls/VectorBT-Tearsheets (vectorbt + quantstats integration)
    - quantstats.readthedocs.io

Usage::

    from packages.backtest_engine.src.tearsheet import (
        generate_tearsheet,
        generate_snapshot,
        compare_strategies,
        save_tearsheet,
    )

    html = generate_tearsheet(returns, benchmark_returns=nifty_returns, title="EMA Strategy")
    save_tearsheet(html, "/tmp/ema_strategy.html")
"""

from __future__ import annotations

import io
import logging
import textwrap
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    import pandas as pd

logger = logging.getLogger("flinttrade.backtest.tearsheet")

# ---------------------------------------------------------------------------
# Optional import — quantstats
# ---------------------------------------------------------------------------

try:
    import quantstats as qs  # type: ignore[import-untyped]

    _QS_AVAILABLE = True
    qs.extend_pandas()  # Adds .sharpe(), .sortino(), etc. to pd.Series
except ImportError:
    qs = None  # type: ignore[assignment]  # Kept as a patchable name for tests.
    _QS_AVAILABLE = False
    logger.debug(
        "quantstats not installed. Tearsheet generation will return stub HTML. "
        "Install with: pip install quantstats"
    )


