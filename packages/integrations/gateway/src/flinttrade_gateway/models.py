"""Pydantic models for the FlintTrade broker gateway."""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum
from typing import Any

from pydantic import BaseModel


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------


class AuthFlowType(StrEnum):
    """Authentication flow required by a broker.

    Variants:
        oauth_redirect: Standard OAuth2 redirect — user is sent to broker's
            login page and returned with an authorisation code.
        totp_form: Credential form with client ID, password, and a
            time-based OTP (TOTP) generated by an authenticator app.
        api_key_direct: Static API key supplied once; no interactive login
            required per session.
        otp_sms: Single-step OTP delivered via SMS — user submits the code
            to complete authentication.
        otp_multistep: Multi-step OTP flow requiring several round-trips to
            the broker's API before a session token is obtained.  Used by
            brokers such as Samco whose 2FA involves:
            (1) request OTP → OTP sent to mobile,
            (2) submit OTP → secret key e-mailed to user,
            (3) generate access token from secret key,
            (4) login with access token + password → session token.
    """

    oauth_redirect = "oauth_redirect"
    totp_form = "totp_form"
    api_key_direct = "api_key_direct"
    otp_sms = "otp_sms"
    otp_multistep = "otp_multistep"


class AccountStatus(StrEnum):
    """Connection status of a broker account."""

    disconnected = "disconnected"
    authenticating = "authenticating"
    connected = "connected"
    error = "error"
    token_expired = "token_expired"


